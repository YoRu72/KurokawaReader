export function icon(name: keyof typeof PATHS | string): SVGElement {
  const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
  svg.setAttribute('viewBox', '0 0 24 24');
  svg.setAttribute('aria-hidden', 'true');
  svg.innerHTML = PATHS[name] ?? PATHS.more;
  return svg;
}

export function iconButton(name: string, label: string, onClick?: (e: MouseEvent) => void, opts: { pressed?: boolean; text?: boolean } = {}): HTMLButtonElement {
  const b = h('button', { class: 'icon-btn' + (opts.text ? ' has-label' : ''), type: 'button', title: label, 'aria-label': label }, icon(name), opts.text ? h('span', null, label) : null);
  if (opts.pressed !== undefined) b.setAttribute('aria-pressed', String(opts.pressed));
  if (onClick) b.addEventListener('click', onClick);
  return b;
}

let toastTimer: number | undefined;
export function toast(msg: string, kind: 'info' | 'error' = 'info', ms = 2200): void {
  document.querySelectorAll('.toast').forEach((t) => t.remove());
  const el = h('div', { class: 'toast' + (kind === 'error' ? ' error' : ''), role: 'status' }, msg);
  document.body.appendChild(el);
  window.clearTimeout(toastTimer);
  toastTimer = window.setTimeout(() => el.remove(), ms);
}

/** A bottom sheet. Returns the body element and a close function. */
export function openSheet(title: string, closeLabel: string): { body: HTMLElement; actions: HTMLElement; close: () => void; el: HTMLElement } {
  document.querySelectorAll('.sheet, .sheet-scrim').forEach((s) => s.remove());
  const body = h('div', { class: 'sheet-body' });
  const actions = h('div', { class: 'sheet-actions' });
  const close = () => { el.remove(); scrim.remove(); };
  const el = h('div', { class: 'sheet', role: 'dialog', 'aria-label': title },
    h('div', { class: 'sheet-head' }, h('h3', null, title), iconButton('close', closeLabel, close)),
    body, actions);
  const scrim = h('div', { class: 'scrim sheet-scrim', onclick: close });
  document.body.append(scrim, el);
  return { body, actions, close, el };
}

export function debounce<T extends (...a: never[]) => void>(fn: T, ms: number): T {
  let t: number | undefined;
  return ((...args: never[]) => { window.clearTimeout(t); t = window.setTimeout(() => fn(...args), ms); }) as T;
}

export function throttle<T extends (...a: never[]) => void>(fn: T, ms: number): T {
  let last = 0; let t: number | undefined;
  return ((...args: never[]) => {
    const now = Date.now();
    const run = () => { last = now; fn(...args); };
    if (now - last >= ms) run();
    else { window.clearTimeout(t); t = window.setTimeout(run, ms - (now - last)); }
  }) as T;
}

export function escapeHtml(s: string): string {
  return s.replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]!);
}

/** Deterministic warm palette for generated covers. */
export function coverColors(seed: string): [string, string] {
  let hsh = 0;
  for (const ch of seed) hsh = (hsh * 31 + ch.charCodeAt(0)) >>> 0;
  const hue = hsh % 360;
  return [`hsl(${hue} 28% 30%)`, `hsl(${(hue + 40) % 360} 32% 18%)`];
}

// Build script: bundles src/main.ts with esbuild, copies static files,
// vendors the pdf.js worker and writes a precaching service worker so the
// whole app works offline.
import * as esbuild from 'esbuild';
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dist = path.join(root, 'dist');
const args = new Set(process.argv.slice(2));
const watch = args.has('--watch');
const serve = args.has('--serve');

async function copyDir(src, dest) {
  await fs.mkdir(dest, { recursive: true });
  for (const entry of await fs.readdir(src, { withFileTypes: true })) {
    const s = path.join(src, entry.name);
    const d = path.join(dest, entry.name);
    if (entry.isDirectory()) await copyDir(s, d);
    else await fs.copyFile(s, d);
  }
}

async function walk(dir, base = dir, out = []) {
  for (const entry of await fs.readdir(dir, { withFileTypes: true })) {
    const p = path.join(dir, entry.name);
    if (entry.isDirectory()) await walk(p, base, out);
    else out.push('/' + path.relative(base, p).split(path.sep).join('/'));
  }
  return out;
}

async function copyStatic() {
  await fs.rm(dist, { recursive: true, force: true });
  await fs.mkdir(path.join(dist, 'assets'), { recursive: true });
  await copyDir(path.join(root, 'public'), dist);
  // pdf.js worker must be a separate file loaded by the browser.
  // Built from the readable worker with a small patch (ActualText in extracted text; see the script).
  const { buildPdfWorker } = await import('./patch-pdfjs.mjs');
  await buildPdfWorker(path.join(dist, 'assets', 'pdf.worker.min.mjs'));
  // pdf.js side resources: CMaps (CID fonts), standard fonts, image decoders (JPX/JBIG2 as WASM), ICC profiles.
  const pdfRoot = path.dirname(require.resolve('pdfjs-dist/package.json'));
  for (const dir of ['cmaps', 'standard_fonts', 'wasm', 'iccs']) {
    try { await copyDir(path.join(pdfRoot, dir), path.join(dist, 'assets', 'pdfjs', dir)); } catch { /* optional */ }
  }
}

/** The chunks the app's entry loads before anything is shown, declared in index.html so the browser fetches them
 *  all at once instead of discovering them one import at a time (a waterfall thirty-odd requests deep on a phone). */
async function preloadStartupChunks() {
  const assets = path.join(dist, 'assets');
  const seen = new Set(); const order = [];
  const visit = async (file) => {
    if (seen.has(file)) return; seen.add(file);
    let src = ''; try { src = await fs.readFile(path.join(assets, file), 'utf8'); } catch { return; }
    // Static imports only: `import{...}from"./chunk-x.js"` and `import"./chunk-x.js"` — dynamic ones are not startup.
    for (const m of src.matchAll(/(?:^|[;}\s])import(?:[^"'()]*?from)?\s*["'](\.\/[^"']+\.js)["']/g)) await visit(m[1].slice(2));
    if (file !== 'app.js') order.push(file);
  };
  await visit('app.js');
  const fonts = (await fs.readdir(path.join(assets, 'fonts'))).filter((f) => /^(Inter|Sultan-Medium)-/.test(f) && f.endsWith('.woff2'));
  const tags = [...order.map((f) => `  <link rel="modulepreload" href="assets/${f}" />`), ...fonts.map((f) => `  <link rel="preload" href="assets/fonts/${f}" as="font" type="font/woff2" crossorigin />`)].join('\n');
  const html = path.join(dist, 'index.html');
  await fs.writeFile(html, (await fs.readFile(html, 'utf8')).replace('  <link rel="stylesheet" href="assets/app.css" />', `  <link rel="stylesheet" href="assets/app.css" />\n${tags}`));
  return order.length;
}

async function writeServiceWorker() {
  const files = (await walk(dist)).filter((f) => f !== '/sw.js' && !f.endsWith('.map'));
  const version = Date.now().toString(36);
  const sw = `// Generated by scripts/build.mjs — precaches the whole app for offline use.
const CACHE = 'kurokawa-${version}';
const BASE = new URL(self.registration.scope).pathname.replace(/\\/$/, '');
const ASSETS = new Set(${JSON.stringify(['/', ...files], null, 0)}.map((p) => BASE + p));
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll([...ASSETS])).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== CACHE && k !== 'kurokawa-ext').map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', (e) => {
  const url = new URL(e.request.url);
  if (e.request.method !== 'GET') return;
  // Optional components fetched once from a CDN (the Japanese dictionary): cache-first, kept across app updates.
  if (url.host === 'cdn.jsdelivr.net' && (url.pathname.includes('/kuromoji') || url.pathname.includes('/pinyin-pro'))) {
    e.respondWith(caches.open('kurokawa-ext').then((c) => c.match(e.request).then((hit) => hit || fetch(e.request).then((res) => { if (res.ok) c.put(e.request, res.clone()); return res; }))));
    return;
  }
  if (url.origin !== location.origin) return;
  // Book files streamed from device storage (Capacitor) and anything that is not an app asset stay out of the cache.
  if (url.pathname.startsWith('/_capacitor_') || !(url.pathname === BASE + '/' || ASSETS.has(url.pathname) || url.pathname.startsWith(BASE + '/assets/'))) return;
  e.respondWith(
    caches.match(e.request, { ignoreSearch: true }).then((hit) => hit || fetch(e.request).then((res) => {
      const copy = res.clone();
      caches.open(CACHE).then((c) => c.put(e.request, copy));
      return res;
    }).catch(() => caches.match(BASE + '/index.html')))
  );
});
`;
  await fs.writeFile(path.join(dist, 'sw.js'), sw);
}

const buildOptions = {
  entryPoints: { app: path.join(root, 'src/main.ts'), scanworker: path.join(root, 'src/scanworker.ts'), pdflayout: path.join(root, 'src/pdflayout.worker.ts'), thumbworker: path.join(root, 'src/sources/thumb.worker.ts') },
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: ['es2022', 'chrome100', 'safari16', 'firefox110'],
  outdir: path.join(dist, 'assets'),
  entryNames: '[name]',
  splitting: true,
  chunkNames: 'chunk-[name]-[hash]',
  assetNames: 'fonts/[name]-[hash]',
  minify: !watch && !process.env.NOMINIFY,
  sourcemap: true,
  loader: { '.ttf': 'file', '.woff2': 'file', '.svg': 'file' },
  logLevel: 'info',
  plugins: [(await import('./patch-pdfjs.mjs')).pdfjsMainPlugin],
  define: { 'process.env.NODE_ENV': watch ? '"development"' : '"production"', __APP_VERSION__: JSON.stringify(JSON.parse(await fs.readFile(path.join(root, 'package.json'), 'utf8')).version) },
};

// The extension sandbox's runtime: built alone (no app code, no chunks), inlined into a frame at run time.
const runtimeOptions = {
  entryPoints: { 'ext-runtime': path.join(root, 'src/sources/ext/rt/runtime.ts') },
  bundle: true, format: 'iife', platform: 'browser', target: ['es2020', 'chrome90', 'safari15', 'firefox100'],
  outdir: path.join(dist, 'assets'), entryNames: '[name]', minify: !watch && !process.env.NOMINIFY, sourcemap: false, logLevel: 'warning',
};

await copyStatic();
if (watch || serve) {
  const ctx = await esbuild.context(buildOptions);
  const rctx = await esbuild.context(runtimeOptions);
  if (watch) { await ctx.watch(); await rctx.watch(); }
  else { await ctx.rebuild(); await rctx.rebuild(); }
  if (!watch) await preloadStartupChunks();
  await writeServiceWorker();
  if (serve) {
    const { hosts, port } = await ctx.serve({ servedir: dist, port: 5173 });
    console.log(`KurokawaReader → http://${hosts?.[0] ?? '127.0.0.1'}:${port}`);
  }
} else {
  await esbuild.build(buildOptions);
  await esbuild.build(runtimeOptions);
  const n = await preloadStartupChunks();
  await writeServiceWorker();
  console.log(`Built → dist/ (${n} startup chunks preloaded)`);
}

const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('kurokawaDesktop', {
  onOpenFile(cb) { ipcRenderer.on('kr:open-file', (_e, payload) => cb(payload)); ipcRenderer.invoke('kr:ready'); },
  platform: process.platform,
  installUpdate(url, opts) { return ipcRenderer.invoke('kr:install-update', url, opts); },
  downloadUpdate(opts) { return ipcRenderer.invoke('kr:update-download', opts); },
  installDownloadedUpdate() { return ipcRenderer.invoke('kr:update-install'); },
  onUpdateProgress(cb) { ipcRenderer.removeAllListeners('kr:update-progress'); ipcRenderer.on('kr:update-progress', (_e, p) => cb(p)); },
  isPortable() { return ipcRenderer.invoke('kr:is-portable'); },
  scanDevice(exts) { return ipcRenderer.invoke('kr:scan-device', exts); },
  readFile(p) { return ipcRenderer.invoke('kr:read-file', p); },
  openDefaultApps() { return ipcRenderer.invoke('kr:default-apps'); },
  setFullscreen(v) { return ipcRenderer.invoke('kr:fullscreen', v); },
  setImmersive(on) { return ipcRenderer.invoke('kr:immersive', on); },
  copyImage(b64) { return ipcRenderer.invoke('kr:copy-image', b64); },
  printToPdf(html, opts) { return ipcRenderer.invoke('kr:print-pdf', html, opts); },
  http(o) { return ipcRenderer.invoke('kr:http', o); },
  openWebView(url) { return ipcRenderer.invoke('kr:open-webview', url); },
  pickFolder() { return ipcRenderer.invoke('kr:folder-pick'); },
  readTextFile(p) { return ipcRenderer.invoke('kr:folder-read', p); },
  writeTextFile(p, text) { return ipcRenderer.invoke('kr:folder-write', p, text); },
  download(url, name) { return ipcRenderer.invoke('kr:download', url, name); },
  deleteDownload(p) { return ipcRenderer.invoke('kr:delete-download', p); },
  onDownloadProgress(cb) { ipcRenderer.removeAllListeners('kr:download-progress'); ipcRenderer.on('kr:download-progress', (_e, p) => cb(p)); },
  writeBinary(p, b64, append) { return ipcRenderer.invoke('kr:write-binary', p, b64, !!append); },
  onOpenUrl(cb) { ipcRenderer.on('kr:open-url', (_e, u) => cb(u)); },
  onCommand(cb) { ipcRenderer.on('kr:command', (_e, c) => cb(c)); },
  setProgress(p) { ipcRenderer.send('kr:progress', p); },
});

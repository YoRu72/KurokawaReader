// Build: bundles src/main.ts with esbuild, copies public/, writes a precaching service worker (the same shape as
// the reader's, without its PDF pieces).
import * as esbuild from 'esbuild';
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dist = path.join(root, 'dist');
const args = new Set(process.argv.slice(2));
const watch = args.has('--watch'); const serve = args.has('--serve');

async function copyDir(src, dest) {
  await fs.mkdir(dest, { recursive: true });
  for (const e of await fs.readdir(src, { withFileTypes: true })) { const s = path.join(src, e.name), d = path.join(dest, e.name); if (e.isDirectory()) await copyDir(s, d); else await fs.copyFile(s, d); }
}
async function walk(dir, base = dir, out = []) {
  for (const e of await fs.readdir(dir, { withFileTypes: true })) { const p = path.join(dir, e.name); if (e.isDirectory()) await walk(p, base, out); else out.push('/' + path.relative(base, p).split(path.sep).join('/')); }
  return out;
}
async function preload() {
  const assets = path.join(dist, 'assets'); const seen = new Set(); const order = [];
  const visit = async (file) => { if (seen.has(file)) return; seen.add(file); let src = ''; try { src = await fs.readFile(path.join(assets, file), 'utf8'); } catch { return; } for (const m of src.matchAll(/(?:^|[;}\s])import(?:[^"'()]*?from)?\s*["'](\.\/[^"']+\.js)["']/g)) await visit(m[1].slice(2)); if (file !== 'app.js') order.push(file); };
  await visit('app.js');
  const fonts = (await fs.readdir(path.join(assets, 'fonts')).catch(() => [])).filter((f) => /^(Inter|Sultan-Medium)-/.test(f) && f.endsWith('.woff2'));
  const tags = [...order.map((f) => `  <link rel="modulepreload" href="assets/${f}" />`), ...fonts.map((f) => `  <link rel="preload" href="assets/fonts/${f}" as="font" type="font/woff2" crossorigin />`)].join('\n');
  const html = path.join(dist, 'index.html');
  await fs.writeFile(html, (await fs.readFile(html, 'utf8')).replace('  <link rel="stylesheet" href="assets/app.css" />', `  <link rel="stylesheet" href="assets/app.css" />\n${tags}`));
}
async function sw() {
  const files = (await walk(dist)).filter((f) => f !== '/sw.js' && !f.endsWith('.map'));
  const version = Date.now().toString(36);
  await fs.writeFile(path.join(dist, 'sw.js'), `// Generated by scripts/build.mjs — the app precached for offline use.
const CACHE = 'kurokawa-tools-${version}';
const BASE = new URL(self.registration.scope).pathname.replace(/\\/$/, '');
const ASSETS = new Set(${JSON.stringify(['/', ...files])}.map((p) => BASE + p));
self.addEventListener('install', (e) => { e.waitUntil(caches.open(CACHE).then((c) => c.addAll([...ASSETS])).then(() => self.skipWaiting())); });
self.addEventListener('activate', (e) => { e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim())); });
self.addEventListener('fetch', (e) => {
  const url = new URL(e.request.url);
  if (e.request.method !== 'GET' || url.origin !== location.origin) return;
  if (!(url.pathname === BASE + '/' || ASSETS.has(url.pathname) || url.pathname.startsWith(BASE + '/assets/'))) return;
  e.respondWith(caches.match(e.request, { ignoreSearch: true }).then((hit) => hit || fetch(e.request).then((res) => { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(e.request, copy)); return res; }).catch(() => caches.match(BASE + '/index.html'))));
});
`);
}
const pkg = JSON.parse(await fs.readFile(path.join(root, 'package.json'), 'utf8'));
const options = {
  entryPoints: { app: path.join(root, 'src/main.ts') },
  bundle: true, format: 'esm', platform: 'browser', target: ['es2022', 'chrome100', 'safari16', 'firefox110'],
  outdir: path.join(dist, 'assets'), entryNames: '[name]', splitting: true, chunkNames: 'chunk-[name]-[hash]', assetNames: 'fonts/[name]-[hash]',
  minify: !watch && !process.env.NOMINIFY, charset: 'utf8', sourcemap: watch || !!process.env.KR_MAPS,
  loader: { '.ttf': 'file', '.woff2': 'file', '.svg': 'file' }, logLevel: 'info',
  define: { 'process.env.NODE_ENV': watch ? '"development"' : '"production"', __APP_VERSION__: JSON.stringify(pkg.version), __REPO_SLUG__: JSON.stringify(process.env.GITHUB_REPOSITORY || 'YoRu72/KurokawaReader') },
};
await fs.rm(dist, { recursive: true, force: true });
await copyDir(path.join(root, 'public'), dist);
if (watch || serve) {
  const ctx = await esbuild.context(options);
  if (watch) await ctx.watch(); else await ctx.rebuild();
  if (!watch) await preload();
  await sw();
  if (serve) { const { hosts, port } = await ctx.serve({ servedir: dist, port: 5174 }); console.log(`Kurokawa Tools → http://${hosts?.[0] ?? '127.0.0.1'}:${port}`); }
} else {
  await esbuild.build(options);
  await preload(); await sw();
  console.log('Built → dist/');
}

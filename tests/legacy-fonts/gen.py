import json; from labels import SCHEMES
h=json.load(open('hashes.json')); tab={}
for n,s in SCHEMES.items():
  for g,(hv,b) in h[n].items():
    if g in s: tab[hv]=[s[g].replace('_',' ')]+([round(b[0]),round(b[2])] if b else [0,0])
import sys
out=sys.argv[1]
items=sorted(tab.items())
js = ("/* Unicode text (and ink extent: left and right edge, 1/1000 em) of the glyphs of the Advent (3B2) Arabic fonts — legacy fonts that file letters under Latin\n"
      " * codes and carry no /ToUnicode. Keyed by an FNV-1a hash of each glyph's Type 2 charstring, so a glyph is\n"
      " * recognised in any PDF whatever its font is called. Generated by tests/legacy-fonts/gen.py. */\n"
      "const KR_LEGACY_GLYPHS = new Map(" + json.dumps(items, ensure_ascii=False, separators=(',',':')) + ");\n")
open(out,'w').write(js); print(len(items))
